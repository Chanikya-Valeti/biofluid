#!/usr/bin/env python3
"""Write system/blockMeshDict for the FDA benchmark nozzle (sudden-expansion
orientation), with the flow along +y and the sudden expansion at y = 0.

    inlet pipe      D = 12 mm, from y = -122.685 mm to the cone
    conical cone    20 degree included angle, 12 mm -> 4 mm,
                    y = -62.685 mm ... -40 mm (length 22.685 mm)
    throat          d = 4 mm, y = -40 mm ... 0
    sudden expansion to D = 12 mm at y = 0; outlet pipe to y = +120 mm

Block topology: upstream of the expansion every cross-section is a 5-block
O-grid whose radius follows the wall. Downstream, the same O-grid (radius
2 mm) continues as the jet core and an outer ring of four blocks fills the
space out to 6 mm; the upstream face of the ring is the expansion step.

Only the Python standard library is needed.
"""
import math
from pathlib import Path

D_IN = 0.012
R_IN = D_IN / 2
R_T = 0.002                                  # throat radius
HALF_ANGLE = math.radians(10.0)
L_CONE = (R_IN - R_T) / math.tan(HALF_ANGLE)  # 22.685 mm
L_THROAT = 0.040
L_INLET = 5 * D_IN
L_OUT = 0.120
Y_THROAT = -L_THROAT
Y_CONE = Y_THROAT - L_CONE
Y_IN = Y_CONE - L_INLET

N_CORE = 10          # cells along each core side and circumferentially per block
N_RAD = 10           # core square -> 2 mm cylinder (or the wall upstream)
N_RING = 18          # 2 mm -> 6 mm in the outlet pipe
CORE = 0.45          # core square half-diagonal as a fraction of the radius
CORNERS = [45.0, 135.0, 225.0, 315.0]

# (y, radius, n_axial to next station, axial grading to next station)
UPSTREAM = [(Y_IN, R_IN, 20, 0.5), (Y_CONE, R_IN, 0, 1.0)]
N_CONE = 24
for i in range(1, N_CONE + 1):
    y = Y_CONE + L_CONE * i / N_CONE
    UPSTREAM[-1] = UPSTREAM[-1][:2] + (1, 1.0)
    UPSTREAM.append((y, R_IN - (R_IN - R_T) * i / N_CONE, 0, 1.0))
UPSTREAM[-1] = UPSTREAM[-1][:2] + (60, 1.0)  # throat
DOWNSTREAM = [(0.0, R_T, 120, 6.0), (L_OUT, R_T, 0, 1.0)]
STATIONS = UPSTREAM + DOWNSTREAM
K0 = len(UPSTREAM)                           # index of the y = 0 station

HEADER = r"""/*--------------------------------*- C++ -*----------------------------------*\
| =========                 |                                                 |
| \\      /  F ield         | OpenFOAM: The Open Source CFD Toolbox           |
|  \\    /   O peration     | Version:  v2412                                 |
|   \\  /    A nd           | Website:  www.openfoam.com                      |
|    \\/     M anipulation  |                                                 |
\*---------------------------------------------------------------------------*/
FoamFile
{
    version     2.0;
    format      ascii;
    class       dictionary;
    object      blockMeshDict;
}
// * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * //
"""


def P(y, a, b):
    """Cross-section point (a, b) at axial position y; a -> z, b -> x."""
    return f"({b:.8g} {y:.8g} {a:.8g})"


def main():
    n = len(STATIONS)
    lines = []
    w = lines.append
    w("// FDA benchmark nozzle, sudden-expansion orientation (flow along +y).")
    w("// Generated by system/makeBlockMeshDict.py - edit that script, not this file.")
    w("")
    w("scale 1;")
    w("")
    w("vertices")
    w("(")
    for k, (y, r, *_r) in enumerate(STATIONS):
        a = CORE * r / math.sqrt(2.0)
        for m, th in enumerate(CORNERS):
            t = math.radians(th)
            w(f"    {P(y, math.copysign(a, math.cos(t)), math.copysign(a, math.sin(t)))}  // {8*k+m}")
        for m, th in enumerate(CORNERS):
            t = math.radians(th)
            w(f"    {P(y, r*math.cos(t), r*math.sin(t))}  // {8*k+4+m}")
    ring0 = 8 * n
    for j, k in enumerate(range(K0, n)):
        y = STATIONS[k][0]
        for m, th in enumerate(CORNERS):
            t = math.radians(th)
            w(f"    {P(y, R_IN*math.cos(t), R_IN*math.sin(t))}  // {ring0+4*j+m} ring")
    w(");")
    w("")

    def ci(k, m):
        return 8 * k + (m % 4)

    def oi(k, m):
        return 8 * k + 4 + (m % 4)

    def ri(k, m):
        return ring0 + 4 * (k - K0) + (m % 4)

    w("blocks")
    w("(")
    for k in range(n - 1):
        nx, gx = STATIONS[k][2], STATIONS[k][3]
        c0 = [ci(k, m) for m in range(4)]
        c1 = [ci(k + 1, m) for m in range(4)]
        w(f"    hex ({' '.join(map(str, c0 + c1))}) ({N_CORE} {N_CORE} {nx}) simpleGrading (1 1 {gx})")
        for m in range(4):
            v = [ci(k, m), oi(k, m), oi(k, m + 1), ci(k, m + 1),
                 ci(k + 1, m), oi(k + 1, m), oi(k + 1, m + 1), ci(k + 1, m + 1)]
            w(f"    hex ({' '.join(map(str, v))}) ({N_RAD} {N_CORE} {nx}) simpleGrading (0.5 1 {gx})")
        if k >= K0:
            for m in range(4):
                v = [oi(k, m), ri(k, m), ri(k, m + 1), oi(k, m + 1),
                     oi(k + 1, m), ri(k + 1, m), ri(k + 1, m + 1), oi(k + 1, m + 1)]
                w(f"    hex ({' '.join(map(str, v))}) ({N_RING} {N_CORE} {nx}) "
                  f"simpleGrading (2.5 1 {gx})")
    w(");")
    w("")

    w("edges")
    w("(")
    for k, (y, r, *_r) in enumerate(STATIONS):
        a = CORE * r / math.sqrt(2.0)
        for m in range(4):
            tm = math.radians(CORNERS[m] + 45.0)
            w(f"    arc {oi(k, m)} {oi(k, m + 1)} {P(y, r*math.cos(tm), r*math.sin(tm))}")
            w(f"    arc {ci(k, m)} {ci(k, m + 1)} {P(y, 1.1*a*math.cos(tm), 1.1*a*math.sin(tm))}")
    for k in range(K0, n):
        y = STATIONS[k][0]
        for m in range(4):
            tm = math.radians(CORNERS[m] + 45.0)
            w(f"    arc {ri(k, m)} {ri(k, m + 1)} {P(y, R_IN*math.cos(tm), R_IN*math.sin(tm))}")
    w(");")
    w("")

    def core_end(k):
        f = [f"({' '.join(str(ci(k, m)) for m in range(4))})"]
        f += [f"({ci(k, m)} {oi(k, m)} {oi(k, m + 1)} {ci(k, m + 1)})" for m in range(4)]
        return f

    inlet = core_end(0)
    outlet = core_end(n - 1) + [f"({oi(n-1, m)} {ri(n-1, m)} {ri(n-1, m+1)} {oi(n-1, m+1)})"
                                for m in range(4)]
    wall = []
    for k in range(K0):
        wall += [f"({oi(k, m)} {oi(k, m+1)} {oi(k+1, m+1)} {oi(k+1, m)})" for m in range(4)]
    # expansion step (upstream face of the ring blocks)
    wall += [f"({oi(K0, m)} {ri(K0, m)} {ri(K0, m+1)} {oi(K0, m+1)})" for m in range(4)]
    for k in range(K0, n - 1):
        wall += [f"({ri(k, m)} {ri(k, m+1)} {ri(k+1, m+1)} {ri(k+1, m)})" for m in range(4)]

    w("boundary")
    w("(")
    for name, typ, faces, extra in (
        ("INLET", "mappedPatch", inlet,
         ["sampleMode nearestCell;", "sampleRegion region0;", "samplePatch none;",
          f"offset (0 {2*D_IN:g} 0);"]),
        ("OUTLET", "patch", outlet, []),
        ("WALL", "wall", wall, []),
    ):
        w(f"    {name}")
        w("    {")
        w(f"        type {typ};")
        for e in extra:
            w(f"        {e}")
        w("        faces")
        w("        (")
        for f in faces:
            w(f"            {f}")
        w("        );")
        w("    }")
    w(");")
    w("")
    w("mergePatchPairs ();")

    text = HEADER + "\n" + "\n".join(lines) + "\n\n// ************************************************************************* //\n"
    out = Path(__file__).resolve().parent / "blockMeshDict"
    out.write_text(text)
    print(f"Wrote {out}")


if __name__ == "__main__":
    main()
