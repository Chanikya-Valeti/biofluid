#!/usr/bin/env python3
"""Write an O-grid blockMeshDict for a circular tube along the y-axis.

The tube cross-section is a 5-block O-grid (one square core block and four
outer blocks). The cross-section is repeated at a series of axial stations;
the radius may change from station to station, which is how a stenosis is
represented. Run this script from the case directory to regenerate
system/blockMeshDict; edit the PARAMETERS section to change the geometry.

Only the Python standard library is needed.
"""
import math
from pathlib import Path

HEADER = r"""/*--------------------------------*- C++ -*----------------------------------*\
| =========                 |                                                 |
| \\      /  F ield         | OpenFOAM: The Open Source CFD Toolbox           |
|  \\    /   O peration     | Version:  v2412                                 |
|   \\  /    A nd           | Website:  www.openfoam.com                      |
|    \\/     M anipulation  |                                                 |
\*---------------------------------------------------------------------------*/
FoamFile
{
    version     2.0;
    format      ascii;
    class       dictionary;
    object      blockMeshDict;
}
// * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * //
"""

CORNERS = [45.0, 135.0, 225.0, 315.0]   # O-grid block corners (degrees)


def P(s, a, b):
    """Point from axial coordinate s and cross-section coordinates (a, b).

    The tube axis is y (as in porousValve); (a, b) map to (z, x), a cyclic
    permutation of (x, y, z) so that block orientation stays right-handed.
    """
    return f"({b:.8g} {s:.8g} {a:.8g})"


def ogrid_block_mesh_dict(stations, n_core, n_radial, radial_grading,
                          core_fraction=0.45, description="", mapper=None):
    """Return blockMeshDict text.

    stations : list of (y, radius, n_axial, axial_grading); n_axial and
               axial_grading describe the segment to the *next* station and
               are ignored for the last one.
    n_core   : cells along each side of the core square (and circumferentially
               per outer block).
    n_radial : cells from the core square to the wall.
    radial_grading : last/first cell size in the outer blocks (<1 refines at
               the wall).
    mapper   : optional function (s, a, b) -> (x, y, z) placing the
               cross-section point (a, b) of station s; the default is a
               straight tube along y. Use it for curved vessels.
    """
    if mapper is not None:
        def P(s, a, b):  # noqa: F811 - local override of the straight mapping
            x, y, z = mapper(s, a, b)
            return f"({x:.8g} {y:.8g} {z:.8g})"
    else:
        P = globals()["P"]
    lines = []
    w = lines.append
    if description:
        for d in description.strip().splitlines():
            w(f"// {d}")
        w("// Generated by system/makeBlockMeshDict.py - edit that script, not this file.")
        w("")
    w("scale 1;")
    w("")

    # ---- vertices ----------------------------------------------------------
    w("vertices")
    w("(")
    for k, (x, r, *_rest) in enumerate(stations):
        a = core_fraction * r / math.sqrt(2.0)       # core half-width
        for m, th in enumerate(CORNERS):
            t = math.radians(th)
            y, z = math.copysign(a, math.cos(t)), math.copysign(a, math.sin(t))
            w(f"    {P(x, y, z)}  // {8*k+m} station {k} core")
        for m, th in enumerate(CORNERS):
            t = math.radians(th)
            w(f"    {P(x, r*math.cos(t), r*math.sin(t))}  // {8*k+4+m} station {k} wall")
    w(");")
    w("")

    def ci(k, m):
        return 8 * k + (m % 4)

    def oi(k, m):
        return 8 * k + 4 + (m % 4)

    # ---- blocks ------------------------------------------------------------
    w("blocks")
    w("(")
    for k in range(len(stations) - 1):
        nx, gx = stations[k][2], stations[k][3]
        c0 = [ci(k, m) for m in range(4)]
        c1 = [ci(k + 1, m) for m in range(4)]
        w(f"    hex ({' '.join(map(str, c0 + c1))}) ({n_core} {n_core} {nx}) "
          f"simpleGrading (1 1 {gx})")
        for m in range(4):
            v = [ci(k, m), oi(k, m), oi(k, m + 1), ci(k, m + 1),
                 ci(k + 1, m), oi(k + 1, m), oi(k + 1, m + 1), ci(k + 1, m + 1)]
            w(f"    hex ({' '.join(map(str, v))}) ({n_radial} {n_core} {nx}) "
              f"simpleGrading ({radial_grading} 1 {gx})")
    w(");")
    w("")

    # ---- curved edges ------------------------------------------------------
    w("edges")
    w("(")
    for k, (x, r, *_rest) in enumerate(stations):
        a = core_fraction * r / math.sqrt(2.0)
        for m in range(4):
            tm = math.radians(CORNERS[m] + 45.0)
            w(f"    arc {oi(k, m)} {oi(k, m + 1)} {P(x, r*math.cos(tm), r*math.sin(tm))}")
            rc = 1.1 * a                      # slightly convex core sides
            w(f"    arc {ci(k, m)} {ci(k, m + 1)} {P(x, rc*math.cos(tm), rc*math.sin(tm))}")
    w(");")
    w("")

    # ---- patches -----------------------------------------------------------
    def end_faces(k):
        f = [f"({' '.join(str(ci(k, m)) for m in range(4))})"]
        for m in range(4):
            f.append(f"({ci(k, m)} {oi(k, m)} {oi(k, m + 1)} {ci(k, m + 1)})")
        return f

    last = len(stations) - 1
    w("boundary")
    w("(")
    for name, k in (("INLET", 0), ("OUTLET", last)):
        w(f"    {name}")
        w("    {")
        w("        type patch;")
        w("        faces")
        w("        (")
        for f in end_faces(k):
            w(f"            {f}")
        w("        );")
        w("    }")
    w("    WALL")
    w("    {")
    w("        type wall;")
    w("        faces")
    w("        (")
    for k in range(last):
        for m in range(4):
            w(f"            ({oi(k, m)} {oi(k, m + 1)} {oi(k + 1, m + 1)} {oi(k + 1, m)})")
    w("        );")
    w("    }")
    w(");")
    w("")
    w("mergePatchPairs ();")
    return HEADER + "\n" + "\n".join(lines) + "\n\n// ************************************************************************* //\n"


def write(case_dir, text):
    path = Path(case_dir) / "system" / "blockMeshDict"
    path.write_text(text)
    print(f"Wrote {path}")


# ---------------------------------------------------------------------------
# PARAMETERS: straight artery for the particle-tracking test case
# ---------------------------------------------------------------------------
if __name__ == "__main__":
    R = 0.002          # vessel radius [m]
    L = 0.06           # vessel length [m]
    stations = [
        (0.0, R, 60, 1.0),
        (L,   R, 0,  1.0),
    ]
    text = ogrid_block_mesh_dict(
        stations, n_core=8, n_radial=10, radial_grading=0.6,
        description=(
            "Straight artery along y: R = 2 mm, L = 60 mm (5-block O-grid).\n"
            "The carrier flow is the analytical Poiseuille profile, set by\n"
            "setExprFields, so the mesh only has to resolve it smoothly."
        ),
    )
    write(Path(__file__).resolve().parent.parent, text)
